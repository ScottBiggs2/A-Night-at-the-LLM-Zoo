#!/usr/bin/env python
"""
build_appendix_tables.py -- the LaTeX tables of the conditional-generation
appendix, generated from the scored JSON so that no number is hand-transcribed.

PURE STDLIB, like every other reports/build_*.py. It writes one .tex fragment per
table into --out_dir; the appendix \\input{}s them. Regenerating after a re-run
therefore updates the paper without anyone retyping a digit, which is the whole
point: the first draft of this appendix had a seven-column spec over six-column
rows precisely because the table was maintained by hand.

  python reports/build_appendix_tables.py \\
      --tier "Mini (51M)=reports/data/fn_lomo_mini.json" \\
      --tier "Small (124M)=reports/data/fn_lomo_small.json" \\
      --density reports/data/density_mini_k50.json \\
      --mcd reports/data/mcd_mini_043_r0p4.json ... \\
      --out_dir outputs/tables
"""
from __future__ import annotations

import argparse
import json
import math
import os
import re
import statistics as st

BANNER = ("%% GENERATED by reports/build_appendix_tables.py -- do not edit by hand.\n"
          "%% Regenerate after any re-scoring; every number traces to a JSON.\n")


def read(p):
    with open(p) as f:
        return json.load(f)


def _arm(fn):
    """The single generated arm of a functional report, with its cells."""
    d = fn[0] if isinstance(fn, list) else fn
    g = (d.get("generated") or [None])[0]
    if not g:
        return d, None, None
    arms = g.get("arms") or {}
    if not arms:
        return d, g, None
    return d, g, list(arms.values())[0]


def _t(diffs):
    """Paired mean, standard error and t. Returns NaNs rather than raising on a
    degenerate sample, because a table cell is allowed to be empty."""
    n = len(diffs)
    if n < 2:
        return float("nan"), float("nan"), float("nan"), 0
    m = st.fmean(diffs)
    se = st.stdev(diffs) / math.sqrt(n)
    return m, se, (m / se if se > 0 else float("nan")), n - 1


def tab_ladder(tiers, out_dir):
    """The baseline ladder, per tier, in % dPPL."""
    # The retrieval row is deliberately NOT ladder["retrieval_per_mixture"]. The
    # ladder's own leave-one-mixture-out retrieval and the arm's matched retrieval
    # are two legitimate estimators of the same thing and disagree by ~0.01 pp
    # (5.9967 against 6.0075 at Medium), which is how this table printed 6.00
    # while tab_crps printed 6.01. The matched value is the one a reader compares
    # against the flow, because it is computed on the flow's own cells.
    rows = [("replicate ceiling", "ceiling"),
            ("global mean", "mean_per_mixture"),
            ("linear surface on $\\pi$", "linear_per_mixture"),
            ("quadratic surface on $\\pi$", "quadratic_per_mixture")]
    L = [BANNER, "\\begin{tabular}{l" + "rr" * len(tiers) + "}", "\\toprule"]
    L.append(" & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{k}}}" for k in tiers)
             + " \\\\")
    L.append("".join(f"\\cmidrule(lr){{{2+2*i}-{3+2*i}}}" for i in range(len(tiers))))
    L.append("reference & " + " & ".join(["\\%$\\Delta$PPL & $\\times$ ceil"]
                                         * len(tiers)) + " \\\\")
    L.append("\\midrule")
    for label, key in rows:
        cs = []
        for fn in tiers.values():
            d, _, _ = _arm(fn)
            lad = d["ladder"]
            v, c = lad[key], lad["ceiling"]
            cs.append(f"{v:.2f} & {v/c:.1f}")
        L.append(f"{label} & " + " & ".join(cs) + " \\\\")
    cs = []
    for fn in tiers.values():
        d, _, a = _arm(fn)
        v, c = a["matched_retrieval_pct"], d["ladder"]["ceiling"]
        cs.append(f"{v:.2f} & {v/c:.1f}")
    L.append("retrieval (1-NN, matched blinding) & " + " & ".join(cs) + " \\\\")
    L.append("\\midrule")
    cs = []
    for fn in tiers.values():
        d, _, a = _arm(fn)
        v, c = a["profile_err_pct"], d["ladder"]["ceiling"]
        cs.append(f"\\textbf{{{v:.2f}}} & \\textbf{{{v/c:.1f}}}")
    L.append("\\textbf{flow (ours)} & " + " & ".join(cs) + " \\\\")
    L.append("\\bottomrule")
    L.append("\\end{tabular}")
    write(out_dir, "tab_ladder", L)


def tab_crps(tiers, out_dir):
    """The proper score and the paired tests -- the table the claim rests on.

    SCALES ARE ROWS here, against the column-per-scale convention everywhere else,
    and deliberately. This table holds three statistics per comparison (gap, t, cells
    won) against only three scales; with scales in columns that is either nine stacked
    rows or three-number cells, and both were tried and both read as a mess. Transposed
    it is three rows, every cell one number, and each group of columns headed by what it
    is. Absolute round-trip errors are NOT here -- they are rows of tab_baselines, one
    table earlier in the draft.
    """
    L = [BANNER, "\\begin{tabular}{lrrrrrrrrr}", "\\toprule",
         " & \\multicolumn{3}{c}{CRPS, \\%$\\Delta$PPL}"
         " & \\multicolumn{3}{c}{retrieval $-$ flow, \\%$\\Delta$PPL}"
         " & \\multicolumn{3}{c}{marginal $-$ flow, CRPS} \\\\",
         "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\\cmidrule(lr){8-10}",
         " & flow & marginal & \\textbf{skill}"
         " & gap & $t$ & won & gap & $t$ & won \\\\",
         "\\midrule"]

    def stats(fn, a, b):
        cells = _arm(fn)[2]["cells"]
        m = _t([c[a] - c[b] for c in cells])
        w = sum(1 for c in cells if c[a] > c[b])
        return m[0], m[2], w, len(cells)

    for lab, fn in tiers.items():
        A = _arm(fn)[2]
        g1 = stats(fn, "retrieval_pct", "gen_err_pct")
        g2 = stats(fn, "crps_marginal_pct", "crps_pct")
        L.append(
            f"{lab} & {A['crps_pct']:.2f} & {A['crps_marginal_pct']:.2f}"
            f" & \\textbf{{{A['crps_skill_pct']:+.3f}}}"
            f" & ${g1[0]:+.2f}$ & ${g1[1]:+.2f}$ & {g1[2]}/{g1[3]}"
            f" & ${g2[0]:+.2f}$ & ${g2[1]:+.2f}$ & {g2[2]}/{g2[3]} \\\\")
    L.append("\\bottomrule")
    L.append("\\end{tabular}")

    dfs = sorted({stats(fn, "retrieval_pct", "gen_err_pct")[3] - 1
                  for fn in tiers.values()})
    L.insert(1, "%% for the caption: cells "
             + "/".join(str(x) for x in sorted({_arm(fn)[2]["n_cells"]
                                                for fn in tiers.values()}))
             + ", samples per cell "
             + "/".join(str(_arm(fn)[2]["n_samples_per_cell"])
                        for fn in tiers.values())
             + ", paired df " + "/".join(map(str, dfs))
             + "; a_pi (now appendix-only) "
             + "/".join(f"{_arm(fn)[1]['code_rms_ratio_at_fixed_pi']:.3f}"
                        for fn in tiers.values()))
    write(out_dir, "tab_crps", L)


def _is_vertex(cell):
    """A one-hot mixture, i.e. a simplex vertex. The tolerance is loose because pi
    is stored as float and the anchors are exact one-hots by construction."""
    return max(cell["pi"]) > 0.999


def tab_strata(tiers, out_dir, nstrat=3):
    """The distance axis: does the advantage open up, or close?

    Two things this table stated wrongly before, both checkable from the caption
    alone. The strata are RANK terciles, so naming the rows after the cut points
    implies a thresholding whose counts do not reproduce -- at nstrat = 3 the ranks
    give 29/29/27 where the thresholds give 30/26/29. The edges are now emitted as a
    comment for the caption to quote, and the rows say "tercile".

    And the final row used to be the five cells most distant in nn_l1, captioned as
    the five one-hot vertices. At every scale that set is FOUR one-hots plus one
    interior mixture at max(pi) = 0.474, and it drops a vertex, so the row and its
    caption disagreed. The split is taken on max(pi) instead, which makes the row
    labelled as the vertices the vertices; the interior row beside it is the 80 cells
    a conditional generator is actually asked to serve, and its margin is the larger
    of the two. Distance quantiles cannot substitute, because the vertices are the
    most distant cells and pile into the upper tercile.
    """
    L = [BANNER, "\\begin{tabular}{l" + "rrr" * len(tiers) + "}", "\\toprule"]
    L.append(" & " + " & ".join(f"\\multicolumn{{3}}{{c}}{{{k}}}" for k in tiers)
             + " \\\\")
    L.append("".join(f"\\cmidrule(lr){{{2+3*i}-{4+3*i}}}"
                     for i in range(len(tiers))))
    L.append("stratum & " + " & ".join(["flow & retr. & gap"] * len(tiers))
             + " \\\\")
    L.append("\\midrule")

    # Strata are cut on the FIRST tier's distances and reused verbatim, so the
    # same mixtures fall in the same row at every scale. Cutting each tier on its
    # own quantiles would compare different cells across columns.
    ref = list(tiers.values())[0]
    cuts = sorted(c["nn_l1"] for c in _arm(ref)[2]["cells"])
    edges = [cuts[int(round(i * len(cuts) / nstrat))] for i in range(1, nstrat)]

    def bucket(x):
        return sum(1 for e in edges if x > e)

    ordinal = ["lower", "middle", "upper"]
    names = [(f"{ordinal[b]} tercile" if nstrat == 3 else f"tercile {b + 1}")
             for b in range(nstrat)]

    def row(label, keep):
        cs = []
        for fn in tiers.values():
            cells = [c for c in _arm(fn)[2]["cells"] if keep(c)]
            f = st.fmean(c["gen_err_pct"] for c in cells)
            r = st.fmean(c["retrieval_pct"] for c in cells)
            cs.append(f"{f:.2f} & {r:.2f} & {r-f:+.2f}")
        n = sum(1 for c in _arm(ref)[2]["cells"] if keep(c))
        L.append(f"{label} ($n={n}$) & " + " & ".join(cs) + " \\\\")

    for b in range(nstrat):
        row(names[b], lambda c, b=b: bucket(c["nn_l1"]) == b)
    L.append("\\midrule")
    row("\\emph{interior}", lambda c: not _is_vertex(c))
    row("\\emph{one-hot vertices}", _is_vertex)
    L.append("\\bottomrule")
    L.append("\\end{tabular}")
    L.insert(1, "%% tercile edges in L1 to the nearest surviving mixture: "
                + ", ".join(f"{e:.3f}" for e in edges))
    write(out_dir, "tab_strata", L)


def tab_dose(tiers, out_dir):
    """The slope test: does the REQUESTED weight on a domain move the MEASURED
    perplexity on that domain? A control test, not a quality test -- it is immune
    to the collapse trap, because a collapsed generator draws flat lines however
    flattering its round-trip error.

    One number per cell. Each cell used to hold "slope (r)", which put twelve numbers
    on a row across six columns and made the table unreadable at \\textwidth. The
    correlations are summarised into the caption comment instead: they are a diagnostic
    on whether the relationship is real, and every one of the thirty is negative, so a
    range is the whole of their content.
    """
    L = [BANNER, "\\begin{tabular}{l" + "rr" * len(tiers) + "}", "\\toprule"]
    L.append(" & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{k}}}" for k in tiers)
             + " \\\\")
    L.append("".join(f"\\cmidrule(lr){{{2+2*i}-{3+2*i}}}"
                     for i in range(len(tiers))))
    L.append("domain & " + " & ".join(["real Zoo & flow"] * len(tiers)) + " \\\\")
    L.append("\\midrule")

    ref = list(tiers.values())[0]
    order = [r["domain"] for r in _arm(ref)[0]["dose_response"]]
    fracs = {k: [] for k in tiers}
    rs = []
    for dom in order:
        cs = []
        for name, fn_ in tiers.items():
            d, _, a = _arm(fn_)
            real = {r["domain"]: r for r in d["dose_response"]}[dom]
            gen = {r["domain"]: r for r in a["dose_response"]}[dom]
            cs.append(f"${real['slope']:+.3f}$ & ${gen['slope']:+.3f}$")
            rs += [(abs(real["r"]), dom, "real"), (abs(gen["r"]), dom, "flow")]
            if real["slope"] != 0:
                fracs[name].append(gen["slope"] / real["slope"])
        L.append(f"{dom} & " + " & ".join(cs) + " \\\\")
    L.append("\\midrule")
    cs = []
    for name in tiers:
        f = st.fmean(fracs[name])
        cs.append(f"1.00 & \\textbf{{{f:.2f}}}")
    L.append("mean fraction of real slope & " + " & ".join(cs) + " \\\\")
    L.append("\\bottomrule")
    L.append("\\end{tabular}")
    lo, hi = min(rs), max(rs)
    L.insert(1, f"%% for the caption: all {len(rs)} slopes negative; "
                f"|r| from {lo[0]:.2f} ({lo[1]}, {lo[2]}) to {hi[0]:.2f} "
                f"({hi[1]}, {hi[2]}), every r negative")
    write(out_dir, "tab_dose", L)


def tab_density(denss, out_dir):
    """Likelihood, mutual information and identification, one column per scale.

    Takes an ORDERED mapping label -> density JSON. It was single-tier until
    Medium landed; the scaling trend is the interesting part and a one-column
    table cannot show it.
    """
    if not denss:
        return
    ncol = len(denss)
    L = [BANNER, "\\begin{tabular}{l" + "r" * ncol + "}", "\\toprule",
         "quantity & " + " & ".join(denss) + " \\\\", "\\midrule"]

    def row(label, fmt, get, bold=False):
        """`bold` bolds the LABEL only. Bolding a value is the formatter's job:
        \\textbf{$x$} does not bold math, it silently does nothing, so a bolded
        numeric row has to emit $\\mathbf{x}$ itself."""
        cells = []
        for d in denss.values():
            try:
                v = fmt(get(d))
            except (KeyError, TypeError):
                v = "---"
            cells.append(v)
        lab = f"\\textbf{{{label}}}" if bold else label
        L.append(f"{lab} & " + " & ".join(cells) + " \\\\")

    m4 = lambda v: f"${v:+.4f}$"
    row("conditional NLL (nats/dim)", m4, lambda d: d["nll_pi_per_dim"])
    row("unconditional NLL, matched twin", m4, lambda d: d["nll_uncond_per_dim"])
    row("$I(x;\\pi)$ lower bound (nats)",
        lambda v: f"$\\mathbf{{{v:+.2f}}}$",
        lambda d: d["mi_lower_bound_nats"], bold=True)
    row("\\quad per dimension", m4, lambda d: d["mi_lower_bound_per_dim"])
    L.append("\\midrule")
    row("identification, top-1", lambda v: f"{100*v:.1f}\\%",
        lambda d: d["identification"]["top1"])
    row("identification, top-5", lambda v: f"{100*v:.1f}\\%",
        lambda d: d["identification"]["top5"])
    row("median rank of true $\\pi$", lambda v: f"{v[0]:.1f} / {v[1]}",
        lambda d: (d["identification"]["median_rank"], d["identification"]["n_pi"]))
    row("\\quad chance median rank", lambda v: f"{v:.1f}",
        lambda d: d["identification"]["chance_median_rank"])
    row("InfoNCE (nats, of $\\ln 85 = 4.443$)", lambda v: f"{v:.3f}",
        lambda d: d["identification"]["infonce_nats"])
    row("tie fraction", lambda v: f"{v:.3f}",
        lambda d: d["identification"]["tie_fraction"])
    L.append("\\midrule")
    row("C2ST, joint $(x,\\pi)$", lambda v: f"{v:.3f}",
        lambda d: d["c2st_joint_lead8"])
    row("$k$-NN $\\mathrm{KL}$ (nats)", lambda v: f"${v:+.3f}$",
        lambda d: d["knn_kl_real_to_gen_lead8"])
    row("NN gen$\\to$train / train$\\to$train", lambda v: f"{v:.3f}",
        lambda d: d["nn_ratio"])
    row("trace-vs-map consistency", lambda v: f"{v:.4f}",
        lambda d: d["consistency"]["relative"])
    L.append("\\bottomrule")
    L.append("\\end{tabular}")
    write(out_dir, "tab_density", L)


def _mcd_neighbourhood(d):
    """The blinded neighbourhood, read off the flow directory the run used.

    It used to come from the CLI key, which forced one dict entry per row and so
    four keys per tier; the workaround was trailing spaces, and it emitted a table
    whose scale column was empty on every row and whose neighbourhood column carried
    the tier label. The run already records which ball it was trained against, so
    the label is derived rather than passed.
    """
    fd = os.path.basename(str(d.get("flow_dir", "")).rstrip("/"))
    m = re.search(r"_(\d{3})_r(\d)p(\d+)", fd)
    if not m:
        return fd or "---"
    return f"member {m.group(1)}, $r{{=}}{m.group(2)}.{m.group(3)}$"


def tab_mcd(mcds, out_dir):
    """Meehan-Chaudhuri-Dasgupta, one row per (scale, blinded neighbourhood).

    `mcds` is a list of (tier, record) pairs rather than a dict: several rows share
    a tier, and a dict cannot hold them without mangling the key. Rows are grouped
    by tier with a rule between groups, so a reader can see that the SIGN of Z_U is
    a property of the scale rather than of any one neighbourhood.
    """
    if not mcds:
        return
    L = [BANNER, "\\begin{tabular}{llrrrrl}", "\\toprule",
         "scale & neighbourhood & $n_{\\text{test}}$ & gen$\\to$tr & "
         "test$\\to$tr & $Z_U$ & verdict \\\\", "\\midrule"]
    last = None
    for tier, d in mcds:
        if last is not None and tier != last:
            L.append("\\midrule")
        t = d["three_sample_lead5"]
        shown = tier if tier != last else ""
        L.append(f"{shown} & {_mcd_neighbourhood(d)} & "
                 f"{d['three_sample_n_excluded']} & "
                 f"{t['mean_nn_gen_to_train']:.3f} & "
                 f"{t['mean_nn_test_to_train']:.3f} & "
                 f"${t['Z_U']:+.2f}$ & {t['verdict']} \\\\")
        last = tier
    L.append("\\bottomrule")
    L.append("\\end{tabular}")
    write(out_dir, "tab_mcd", L)


def tab_continuity(path, fn, domain, out_dir):
    """The traverse: a lookup table's staircase against the flow's curve.

    Defined at last. main() has called this since the tables went to three tiers and
    the branch raised NameError, so --path was documented as "do not pass" and the
    fragment on disk was hand-made.

    Retrieval's side comes from the functional report -- `staircase` for the lattice
    count, `paths[domain]` for the traverse -- and the flow's side is computed here
    from the per-request rows, averaging the samples at one request before
    differencing. That averaging is load-bearing: the flow answers every request
    distinctly, so a single draw per request reads sampling noise as wobble.
    """
    rows = [r for r in path.get("rows", []) if r.get("kind") == "path"]
    if not rows:
        print("  [tab] tab_continuity skipped: no path rows in the traverse")
        return
    by_request = {}
    for r in rows:
        by_request.setdefault(r["label"], []).append(r["ppl"][domain])
    vs = [st.fmean(math.log(v) for v in by_request[k]) for k in sorted(by_request)]
    diffs = [b - a for a, b in zip(vs, vs[1:])]
    net = vs[-1] - vs[0]
    tv = sum(abs(x) for x in diffs)
    monotone = sum(1 for x in diffs if x < 0) / len(diffs)

    d = fn[0] if isinstance(fn, list) else fn
    sc, pr, n = d["staircase"], d["paths"][domain], len(vs)

    L = [BANNER, "\\begin{tabular}{lrr}", "\\toprule",
         "quantity & retrieval (1-NN) & flow \\\\", "\\midrule",
         f"distinct answers / requests & {sc['n_distinct_retrieved']} / "
         f"{sc['n_lattice']} ({100*sc['frac_distinct']:.1f}\\%) & "
         f"{n} / {n} (100\\%) \\\\",
         f"mean $L_1$ request $\\to$ answer & "
         f"{sc['mean_l1_to_nearest']:.3f} & $0$ \\\\",
         "\\midrule",
         f"plateaus along the traverse & {pr['n_distinct']} & {n} \\\\",
         f"discontinuities & {pr['jumps']} & $0$ \\\\",
         f"end-to-end $\\Delta \\log \\mathrm{{ppl}}$ (nats) & "
         f"${pr['end_to_end']:.3f}$ & ${net:.3f}$ \\\\",
         f"\\quad as a fraction of retrieval's & $1.000$ & "
         f"${net/pr['end_to_end']:.3f}$ \\\\",
         f"total variation (nats) & {pr['total_variation']:.3f} & {tv:.3f} \\\\",
         f"\\quad over $|$net$|$ & "
         f"{pr['total_variation']/abs(pr['end_to_end']):.2f} & "
         f"{tv/abs(net):.2f} \\\\",
         f"steps in the requested direction & --- & {100*monotone:.1f}\\% \\\\",
         "\\bottomrule", "\\end{tabular}"]
    write(out_dir, "tab_continuity", L)


def tab_scaling(specs, flowmetas, denss, out_dir):
    """The three-scale summary: what moves with size and what does not.

    Deliberately mixes representation, generator and density statistics in one
    table, because the interesting fact is that they do NOT all move together --
    the dispersion caveat weakens with scale while the C2ST does not budge.
    """
    if not specs:
        return
    tiers = list(specs)
    L = [BANNER, "\\begin{tabular}{l" + "r" * len(tiers) + "}", "\\toprule",
         "quantity & " + " & ".join(tiers) + " \\\\", "\\midrule"]

    def row(label, fmt, get, src):
        cells = []
        for t in tiers:
            d = src.get(t)
            try:
                cells.append(fmt(get(d)))
            except (KeyError, TypeError, AttributeError):
                cells.append("---")
        L.append(f"{label} & " + " & ".join(cells) + " \\\\")

    def arch(d):
        return list(d["per_arch"].values())[0]

    L.append("\\multicolumn{%d}{l}{\\emph{the representation}} \\\\" % (len(tiers) + 1))
    row("\\quad $D$ (parameters)", lambda v: f"{v/1e6:.1f}M", lambda d: arch(d)["n_params"], specs)
    row("\\quad transformer blocks", lambda v: f"{v}", lambda d: arch(d)["n_layers"], specs)
    row("\\quad effective rank at $k=99$", lambda v: f"{v:.2f}",
        lambda d: arch(d)["spectrum_effective_rank"], specs)
    row("\\quad $\\lambda_0/\\mathrm{median}$", lambda v: f"{v:.1f}",
        lambda d: arch(d)["spectrum_ev0_over_median"], specs)
    L.append("\\midrule")
    L.append("\\multicolumn{%d}{l}{\\emph{the generator}} \\\\" % (len(tiers) + 1))
    # This is the WHOLE-ZOO flow's training-time statistic, which is NOT the
    # eval-time a_pi of the leave-one-mixture-out flows in tab_crps. They differ
    # substantially (0.707 vs 0.552 at Mini), so the row has to say which one it
    # is; quoting one and comparing it against the other is a real error this
    # label exists to prevent.
    row("\\quad $a_\\pi$, whole-zoo flow at train time", lambda v: f"{v:.3f}",
        lambda d: d["train"]["code_rms_ratio_at_fixed_pi"], flowmetas)
    row("\\quad epochs to early stop (cap $20{,}000$)", lambda v: f"{v:,}",
        lambda d: d["train"]["epochs_run"], flowmetas)
    row("\\quad $\\pi$-code distance correlation", lambda v: f"{v:+.3f}",
        lambda d: d["train"]["pi_code_distance_corr"], flowmetas)
    L.append("\\midrule")
    L.append("\\multicolumn{%d}{l}{\\emph{the density}} \\\\" % (len(tiers) + 1))
    row("\\quad identification top-1 (chance $1.2\\%$)", lambda v: f"{100*v:.1f}\\%",
        lambda d: d["identification"]["top1"], denss)
    row("\\quad InfoNCE (cap $4.443$)", lambda v: f"{v:.3f}",
        lambda d: d["identification"]["infonce_nats"], denss)
    row("\\quad C2ST ($0.5$ indistinguishable)", lambda v: f"{v:.3f}",
        lambda d: d["c2st_joint_lead8"], denss)
    row("\\quad NN gen$\\to$train / train$\\to$train", lambda v: f"{v:.3f}",
        lambda d: d["nn_ratio"], denss)
    L.append("\\bottomrule")
    L.append("\\end{tabular}")
    write(out_dir, "tab_scaling", L)


def _named_arm(fn, want):
    """One arm of a MULTI-arm functional report, by name.

    _arm() takes list(arms.values())[0], which is right for a single-arm
    leave-one-out report and silently wrong for a baseline report carrying
    lomo/soup/trunk/pca_only/anchoronly at once. Prefixes are matched because the
    flow arm is labelled per scale (lomo_mini, lomo_small, ...).
    """
    d = fn[0] if isinstance(fn, list) else fn
    for g in d.get("generated") or []:
        for name, a in (g.get("arms") or {}).items():
            if name == want or name.startswith(want + "_"):
                return d, g, a
    return d, None, None


def tab_baselines(bases, out_dir):
    """Task arithmetic and the reference floors, per tier (\\S app:res:linear).

    Generated rather than hand-written because this appendix's whole claim to
    trustworthiness is that no number in a table was retyped.
    """
    # (label, source). "ladder:<key>" reads the non-generative ladder, "matched:"
    # the retrieval value computed on the flow arm's own cells (see tab_ladder for
    # why that is the one to print), and anything else is a named generated arm's
    # profile_err_pct.
    # Ordered by what each row rules out, not by magnitude: the two reference
    # floors, the generator, the lookup table it has to beat, then the closed-form
    # accounts of pi -> theta in increasing cheapness, then the two diagnostic arms.
    # This subsumes the old separate ladder table, whose linear and quadratic rows
    # were the only thing it added.
    rows = [("replicate ceiling (seed noise)", "ladder:ceiling"),
            ("\\texttt{pca\\_only} (rank-$50$ truncation floor)", "arm:pca_only"),
            ("\\midrule", None),
            ("\\textbf{flow (ours)}", "arm:lomo"),
            ("retrieval (1-NN, matched blinding)", "matched:lomo"),
            ("\\midrule", None),
            ("quadratic surface on $\\pi$", "ladder:quadratic_per_mixture"),
            ("linear surface on $\\pi$", "ladder:linear_per_mixture"),
            ("bare trunk (no branching)", "arm:trunk"),
            ("global mean (ignores $\\pi$)", "ladder:mean_per_mixture"),
            ("\\textbf{soup, Eq.~\\eqref{eq:soup}}", "arm:soup"),
            ("\\midrule", None),
            ("vertices-only flow (App.~\\ref{app:res:vertices})", "arm:anchoronly")]
    L = [BANNER, "\\begin{tabular}{l" + "rr" * len(bases) + "}", "\\toprule",
         " & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{k}}}" for k in bases)
         + " \\\\",
         "".join(f"\\cmidrule(lr){{{2+2*i}-{3+2*i}}}" for i in range(len(bases))),
         "source of weights & "
         + " & ".join(["\\%$\\Delta$PPL & $\\times$ ceil"] * len(bases))
         + " \\\\",
         "\\midrule"]
    for label, src in rows:
        if src is None:
            L.append("\\midrule")
            continue
        cs = []
        for fn in bases.values():
            kind, key = src.split(":", 1)
            d = fn[0] if isinstance(fn, list) else fn
            if kind == "ladder":
                v = d["ladder"][key]
            elif kind == "matched":
                a = _named_arm(fn, key)[2]
                v = a["matched_retrieval_pct"] if a else float("nan")
            else:
                a = _named_arm(fn, key)[2]
                v = a["profile_err_pct"] if a else float("nan")
            c = d["ladder"]["ceiling"]
            if v != v:
                cs.append("--- & ---")
            elif "textbf" in label:
                cs.append(f"\\textbf{{{v:.2f}}} & \\textbf{{{v/c:.1f}}}")
            else:
                cs.append(f"{v:.2f} & {v/c:.1f}")
        L.append(f"{label} & " + " & ".join(cs) + " \\\\")
    L.append("\\bottomrule")
    L.append("\\end{tabular}")
    write(out_dir, "tab_baselines", L)


def write(out_dir, name, lines):
    os.makedirs(out_dir, exist_ok=True)
    p = os.path.join(out_dir, f"{name}.tex")
    with open(p, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"  [tab] {p}")


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--tier", action="append", default=[], metavar="LABEL=PATH")
    p.add_argument("--baseline", action="append", default=[], metavar="LABEL=PATH",
                   help="report_functional.py --json_out carrying the MULTI-arm "
                        "baseline set (lomo/soup/trunk/pca_only/anchoronly), one "
                        "per scale. Drives tab_baselines.")
    p.add_argument("--density", action="append", default=[],
                   metavar="LABEL=PATH",
                   help="report_density.py --out, one per scale.")
    p.add_argument("--mcd", action="append", default=[], metavar="LABEL=PATH")
    p.add_argument("--spectrum", action="append", default=[],
                   metavar="LABEL=PATH",
                   help="pipeline_summary_k*.json, one per scale.")
    p.add_argument("--flowmeta", action="append", default=[],
                   metavar="LABEL=PATH",
                   help="the pi-flow flow_meta.json, one per scale.")
    p.add_argument("--path", default=None,
                   help="eval_generated.py --path output, for the "
                        "continuity table.")
    p.add_argument("--path_domain", default="multilingual")
    p.add_argument("--out_dir", default="outputs/tables")
    a = p.parse_args()

    # rsplit, not split: a label is LaTeX and may legitimately contain "=",
    # as in "$r{=}0.4$". A path never does.
    tiers = {}
    for spec in a.tier:
        lab, path = spec.rsplit("=", 1)
        tiers[lab] = read(path)
    mcds = []
    for spec in a.mcd:
        lab, path = spec.rsplit("=", 1)
        mcds.append((lab, read(path)))

    if tiers:
        tab_ladder(tiers, a.out_dir)
        tab_crps(tiers, a.out_dir)
        tab_strata(tiers, a.out_dir)
        tab_dose(tiers, a.out_dir)
    bases = {}
    for spec in a.baseline:
        lab, path = spec.rsplit("=", 1)
        bases[lab] = read(path)
    if bases:
        tab_baselines(bases, a.out_dir)
    denss = {}
    for spec in a.density:
        lab, path = spec.rsplit("=", 1)
        denss[lab] = read(path)
    if denss:
        tab_density(denss, a.out_dir)
    specs, flowmetas = {}, {}
    for spec in a.spectrum:
        lab, path = spec.rsplit("=", 1)
        specs[lab] = read(path)
    for spec in a.flowmeta:
        lab, path = spec.rsplit("=", 1)
        flowmetas[lab] = read(path)
    if specs:
        tab_scaling(specs, flowmetas, denss, a.out_dir)
    tab_mcd(mcds, a.out_dir)
    if a.path and tiers:
        tab_continuity(read(a.path), list(tiers.values())[0],
                       a.path_domain, a.out_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
